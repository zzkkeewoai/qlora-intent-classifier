"""
5 种 Query 意图类型定义
"""
from enum import Enum


class IntentType(str, Enum):
    FACTUAL = "事实查询"        # "A项目用了什么技术"、"张伟是谁"
    COMPARISON = "对比分析"      # "A和B的技术栈有什么区别"、"对比两个方案"
    INSTRUCTION = "操作指令"     # "帮我生成一份报告"、"把这些数据整理成表格"
    CHITCHAT = "闲聊"           # "你好"、"今天天气不错"、"谢谢"
    AMBIGUOUS = "模糊不清"       # "那个东西怎么样"（指代不明）、"帮我查一下"（没说查什么）


# 每个意图的系统提示词
INTENT_SYSTEM_PROMPT = """你是一个查询意图分类器。请将用户查询分类为以下 5 类之一：

1. 事实查询 - 询问具体事实、数据、定义。如"A项目用了什么技术"、"张伟是谁"
2. 对比分析 - 要求对两个或多个对象进行比较。如"A和B有什么区别"、"对比两个方案"
3. 操作指令 - 要求执行某个操作。如"帮我生成报告"、"整理成表格"
4. 闲聊 - 社交性对话，不涉及具体任务。如"你好"、"谢谢"
5. 模糊不清 - 指代不明、信息不完整、无法判断意图。如"那个怎么样"、"帮我查一下"

请仅输出意图类别名称（事实查询/对比分析/操作指令/闲聊/模糊不清），不要输出任何其他内容。"""

# 每个意图的 Few-shot 示例
FEW_SHOT_EXAMPLES = {
    IntentType.FACTUAL: [
        ("A项目用了什么技术栈", "事实查询"),
        ("张伟是哪个部门的", "事实查询"),
    ],
    IntentType.COMPARISON: [
        ("A项目和B项目的技术栈有什么异同", "对比分析"),
        ("对比一下Python和Go的性能", "对比分析"),
    ],
    IntentType.INSTRUCTION: [
        ("帮我生成一份周报", "操作指令"),
        ("把这份数据整理成表格发到我的邮箱", "操作指令"),
    ],
    IntentType.CHITCHAT: [
        ("你好，今天忙吗", "闲聊"),
        ("谢谢你的帮助", "闲聊"),
    ],
    IntentType.AMBIGUOUS: [
        ("那个东西帮我查一下", "模糊不清"),
        ("怎么样", "模糊不清"),
    ],
}
